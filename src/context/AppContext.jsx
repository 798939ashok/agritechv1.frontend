const AppContext = createContext(null);

export function AppProvider({ children }) {
  const [user, setUser] = useState(() => {
    try { return JSON.parse(localStorage.getItem('agrisense_user')); }
    catch { return null; }
  });
  const [darkMode, setDarkMode] = useState(() => {
    const s = localStorage.getItem('agrisense_darkmode');
    return s === null ? true : s === 'true';
  });
  const [language, setLanguage] = useState(() =>
    localStorage.getItem('agrisense_language') || 'en'
  );
  const [notifications, setNotifications] = useState([
    { id:1, title:'Heavy Rain Alert',    message:'Heavy rain expected tomorrow. Avoid spraying fertilizers.', type:'weather', date:new Date().toISOString(), read:false },
    { id:2, title:'PM Kisan Update',     message:'PM-KISAN 17th instalment released. Check your bank account.', type:'govt', date:new Date().toISOString(), read:false },
    { id:3, title:'Crop Tip of the Day', message:'Apply neem oil spray in the evening to protect against pests.', type:'tip', date:new Date().toISOString(), read:true },
  ]);

  useEffect(() => {
    localStorage.setItem('agrisense_darkmode', darkMode);
    document.body.style.backgroundColor = darkMode ? '#030712' : '#f0fdf4';
    document.body.style.color = darkMode ? '#f9fafb' : '#0f172a';
    document.documentElement.setAttribute('data-theme', darkMode ? 'dark' : 'light');
  }, [darkMode]);

  useEffect(() => {
    localStorage.setItem('agrisense_language', language);
  }, [language]);

  const login  = u  => { setUser(u); localStorage.setItem('agrisense_user', JSON.stringify(u)); };
  const logout = () => { setUser(null); localStorage.removeItem('agrisense_user'); };
  const markAllRead = () => setNotifications(n => n.map(x => ({ ...x, read:true })));
  const unreadCount = notifications.filter(n => !n.read).length;

  return (
    <AppContext.Provider value={{ user, login, logout, darkMode, setDarkMode, language, setLanguage, notifications, setNotifications, markAllRead, unreadCount }}>
      {children}
    </AppContext.Provider>
  );
}

export const useApp = () => useContext(AppContext);

// ✅ useTranslation — same file, always works
export function useTranslation() {
  const { language } = useApp();
  const lang = translations[language] || translations['en'];
  const t = key => lang[key] || translations['en'][key] || key;
  return { t };
}
